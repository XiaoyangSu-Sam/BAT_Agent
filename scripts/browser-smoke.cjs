// Optional UI QA. node scripts/browser-smoke.cjs <playwright-module-dir> [URL]
const fs=require("node:fs"),path=require("node:path");
const {chromium}=require(process.argv[2]?path.resolve(process.argv[2]):"playwright");
(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  const failures=[];page.on("pageerror",e=>failures.push(e.message));
  await page.goto(process.argv[3]||"http://127.0.0.1:8765");
  await page.locator("#providerBadge").filter({hasText:"离线演示"}).waitFor();
  await page.locator("#newSession").click();
  await page.locator("#demo").waitFor({state:"visible"});
  const output=path.resolve(".harness/qa");fs.mkdirSync(output,{recursive:true});
  await page.screenshot({path:path.join(output,"desktop-ready.png"),fullPage:true});
  await page.locator("#demo").click();
  await page.locator("#approval").waitFor({state:"visible",timeout:20000});
  if(!await page.locator("#approvalText").textContent().then(s=>s.includes("run_python_script")))throw Error("Wrong approval");
  await page.screenshot({path:path.join(output,"approval.png"),fullPage:true});
  await page.locator("#approve").click();
  await page.locator("#runStatus").filter({hasText:"已完成"}).waitFor({timeout:20000});
  if(!await page.locator("#messages").textContent().then(s=>s.includes("sum is 15")))throw Error("Missing actual result");
  if(await page.locator("#error").isVisible())throw Error(await page.locator("#error").textContent());
  await page.screenshot({path:path.join(output,"desktop-completed.png"),fullPage:true});
  await page.reload();
  await page.locator("#runStatus").filter({hasText:"已完成"}).waitFor();
  if(!await page.locator("#messages").textContent().then(s=>s.includes("sum is 15")))throw Error("History lost on reload");
  await page.locator("#diagnose").click();
  await page.locator("#diagnosticStatus").filter({hasText:"检测已结束"}).waitFor();
  if(!await page.locator("#diagnosticResult").textContent().then(s=>s.includes("demo_only")))throw Error("Fake mode misrepresented");
  await page.locator("#closeDiagnostic").click();
  await page.locator("#settingsButton").click();
  await page.locator("#settingsDialog").waitFor({state:"visible"});
  await page.locator("#closeSettings").click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(output,"mobile.png"),fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2))throw Error("Mobile horizontal overflow");
  if(failures.length)throw Error(failures.join("\n"));
  await browser.close();
  console.log("Browser QA passed: demo, approval, completion, persisted history, diagnostics, settings, mobile.");
})().catch(e=>{console.error(e);process.exit(1)});
